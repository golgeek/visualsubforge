<details class="shortcut-help">
  <summary>Keyboard shortcuts</summary>
  <p>
    ⌘/Ctrl+Alt+Enter: play/pause while typing (Alt+Space also works when the OS
    allows it) · Alt+←/→: seek 1 s (Shift: 5 s) · Alt+↑/↓: edit previous/next
    cue · In cue rows: Shift+click/arrows selects a range; Ctrl/Cmd+click or
    Space toggles, Ctrl/Cmd+arrows moves focus, Ctrl/Cmd+A selects all · Enter:
    edit selected cue · Escape: return to waveform / cancel held timing. In
    Timing mode, tap Space to play/pause; hold it for at least 400 ms during
    playback to create a cue and keep timing. Press Enter to edit its text.
  </p>
  <p>
    ⌘/Ctrl+Shift+N: create cue · ⌘/Ctrl+Shift+D: delete cue · ⌘/Ctrl+Enter:
    apply text · ⌘/Ctrl+S: save. Right-click the waveform selection or a cue for
    actions. Plain Space remains a text character in the editor.
  </p>
</details>

